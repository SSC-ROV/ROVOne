// 一次性遷移：data/rov.db (SQLite) → Supabase Postgres
// 執行：node --env-file=.env.local scripts/migrate.mjs
import { DatabaseSync } from "node:sqlite";
import postgres from "postgres";

const src = new DatabaseSync("data/rov.db", { readOnly: true });
const sql = postgres(process.env.DATABASE_URL, { prepare: false, max: 1, ssl: "require" });

const DDL = `
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  display_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'member',
  subteam TEXT NOT NULL DEFAULT 'general',
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS mission_tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  points INTEGER,
  sort_order DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE TABLE IF NOT EXISTS cycles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending_leader',
  proposer_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  decided_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  decided_note TEXT NOT NULL DEFAULT '',
  completed_at TEXT,
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE TABLE IF NOT EXISTS tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'todo',
  priority TEXT NOT NULL DEFAULT 'medium',
  subteam TEXT NOT NULL DEFAULT 'general',
  due_date TEXT,
  assignee_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  mission_id INTEGER REFERENCES mission_tasks(id) ON DELETE SET NULL,
  cycle_id INTEGER REFERENCES cycles(id) ON DELETE SET NULL,
  sort_order DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  completed_at TEXT
);
CREATE TABLE IF NOT EXISTS checklist_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0,
  sort_order DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'other',
  date TEXT NOT NULL,
  time TEXT,
  location TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS parts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  spec TEXT NOT NULL DEFAULT '',
  link TEXT NOT NULL DEFAULT '',
  qty INTEGER NOT NULL DEFAULT 1,
  unit TEXT NOT NULL DEFAULT '個',
  est_price DOUBLE PRECISION NOT NULL DEFAULT 0,
  actual_price DOUBLE PRECISION,
  purpose TEXT NOT NULL DEFAULT '',
  subteam TEXT NOT NULL DEFAULT 'general',
  status TEXT NOT NULL DEFAULT 'pending',
  requested_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  decided_at TEXT,
  decided_note TEXT,
  order_vendor TEXT NOT NULL DEFAULT '',
  order_ref TEXT NOT NULL DEFAULT '',
  ordered_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  arrived_at TEXT,
  approve_token TEXT UNIQUE,
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE TABLE IF NOT EXISTS equipment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT '其他',
  note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'available',
  borrower_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  borrowed_at TEXT,
  due_return TEXT,
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE TABLE IF NOT EXISTS dive_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  title TEXT NOT NULL,
  participants TEXT NOT NULL DEFAULT '',
  tested TEXT NOT NULL DEFAULT '',
  issues TEXT NOT NULL DEFAULT '',
  fixes TEXT NOT NULL DEFAULT '',
  next_steps TEXT NOT NULL DEFAULT '',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS cycle_members (
  cycle_id INTEGER NOT NULL REFERENCES cycles(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (cycle_id, user_id)
);
`;

const TABLES = [
  ["users", "id, username, display_name, password_hash, role, subteam, created_at"],
  ["mission_tasks", "id, title, description, points, sort_order, created_at"],
  ["cycles", "id, title, description, start_date, end_date, status, proposer_id, decided_by, decided_note, completed_at, created_at"],
  ["tasks", "id, title, description, status, priority, subteam, due_date, assignee_id, created_by, mission_id, cycle_id, sort_order, created_at, completed_at"],
  ["checklist_items", "id, task_id, text, done, sort_order"],
  ["events", "id, title, type, date, time, location, notes, created_by"],
  ["parts", "id, name, spec, link, qty, unit, est_price, actual_price, purpose, subteam, status, requested_by, decided_at, decided_note, order_vendor, order_ref, ordered_by, arrived_at, approve_token, created_at"],
  ["equipment", "id, name, category, note, status, borrower_id, borrowed_at, due_return, created_at"],
  ["dive_logs", "id, date, title, participants, tested, issues, fixes, next_steps, created_by, created_at"],
  ["cycle_members", "cycle_id, user_id"],
  ["settings", "key, value"],
];

const ID_TABLES = ["users", "mission_tasks", "cycles", "tasks", "checklist_items", "events", "parts", "equipment", "dive_logs"];

async function main() {
  console.log("1) 建立資料表…");
  for (const stmt of DDL.split(";")) {
    const s = stmt.trim();
    if (s) await sql.unsafe(s);
  }
  console.log("2) 遷移資料…");
  for (const [table, cols] of TABLES) {
    const rows = src.prepare(`SELECT ${cols} FROM ${table}`).all();
    if (rows.length === 0) {
      console.log(`   ${table}: 0 筆，略過`);
      continue;
    }
    const colList = cols.split(",").map((c) => `"${c.trim()}"`).join(",");
    for (const row of rows) {
      const vals = cols.split(",").map((c) => {
        const v = row[c.trim()];
        return v === undefined ? null : v;
      });
      await sql.unsafe(
        `INSERT INTO ${table} (${colList}) VALUES (${cols.split(",").map((_, i) => `$${i + 1}`).join(",")}) ON CONFLICT DO NOTHING`,
        vals
      );
    }
    console.log(`   ${table}: ${rows.length} 筆 ✓`);
  }
  console.log("3) 重設流水號…");
  for (const t of ID_TABLES) {
    await sql.unsafe(
      `SELECT setval(pg_get_serial_sequence('${t}','id'), COALESCE((SELECT MAX(id) FROM ${t}), 1))`
    );
  }
  console.log("4) 驗證筆數：");
  for (const [table] of TABLES) {
    const [r] = await sql.unsafe(`SELECT COUNT(*)::int AS c FROM ${table}`);
    console.log(`   ${table}: ${r.c}`);
  }
  await sql.end();
  console.log("遷移完成 ✅");
}

main().catch((e) => {
  console.error("遷移失敗：", e.message);
  process.exit(1);
});
