// Task timeline: comments plus logged changes (status, assignee, priority, due date, project, title).
// Run: node --env-file=.env.local scripts/migrate-task-activity.mjs
import postgres from "postgres";

const sql = postgres(process.env.DATABASE_URL, { prepare: false, max: 1, ssl: "require" });

await sql.unsafe(`
  CREATE TABLE IF NOT EXISTS task_activity (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    kind TEXT NOT NULL,
    body TEXT NOT NULL DEFAULT '',
    meta JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    edited_at TIMESTAMPTZ
  );
  CREATE INDEX IF NOT EXISTS idx_task_activity_task ON task_activity(task_id, created_at);
  ALTER TABLE task_activity ENABLE ROW LEVEL SECURITY;
`);

await sql.end();
console.log("done");
