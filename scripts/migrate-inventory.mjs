// 一次性遷移：庫存表（inventory_items / inventory_locations / inventory_reports）
// API 首次呼叫時也會自動建立；這支腳本只是讓你可以預先建好。
// 執行：node scripts/migrate-inventory.mjs（讀取 .env.local 的 DATABASE_URL）
import postgres from "postgres";
import { readFileSync } from "fs";

const env = readFileSync(".env.local", "utf8");
const url = process.env.DATABASE_URL || env.match(/^DATABASE_URL="?(.+?)"?$/m)?.[1];
const sql = postgres(url, { prepare: false, max: 1, ssl: "require" });

await sql`CREATE TABLE IF NOT EXISTS inventory_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  spec TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  photo TEXT,
  status TEXT NOT NULL DEFAULT 'in_stock',
  status_note TEXT NOT NULL DEFAULT '',
  status_by INTEGER,
  status_at TIMESTAMPTZ,
  created_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
)`;
await sql`CREATE TABLE IF NOT EXISTS inventory_locations (
  item_id INTEGER NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
  location TEXT NOT NULL,
  PRIMARY KEY (item_id, location)
)`;
await sql`CREATE INDEX IF NOT EXISTS inventory_locations_loc_idx ON inventory_locations(location)`;
await sql`CREATE TABLE IF NOT EXISTS inventory_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id INTEGER NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
  status TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  user_id INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
)`;
await sql`CREATE INDEX IF NOT EXISTS inventory_reports_item_idx ON inventory_reports(item_id, created_at DESC)`;
const [{ n }] = await sql`SELECT COUNT(*)::int AS n FROM inventory_items`;
console.log("inventory 表準備完成，目前物品數:", n);
await sql.end();
