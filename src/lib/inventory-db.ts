import { createPartRequest } from "./parts-db";
import {
  compareLocations,
  isInventoryStatus,
  normalizeLocation,
  type InventoryItem,
  type InventoryItemDetail,
  type InventoryReport,
  type InventoryStatus,
} from "./inventory";

/**
 * 庫存資料表。首次呼叫時自動建立（CREATE IF NOT EXISTS），
 * 部署到 Vercel 後不必手動跑遷移；也可用 scripts/migrate-inventory.mjs 預先建立。
 */
let schemaReady: Promise<void> | null = null;

export function ensureInventorySchema(): Promise<void> {
  if (!schemaReady) {
    schemaReady = (async () => {
      await sql`CREATE TABLE IF NOT EXISTS inventory_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        spec TEXT NOT NULL DEFAULT '',
        category TEXT NOT NULL DEFAULT '',
        note TEXT NOT NULL DEFAULT '',
        photo TEXT,
        status TEXT NOT NULL DEFAULT 'in_stock',
        status_note TEXT NOT NULL DEFAULT '',
        status_by INTEGER,
        status_at TIMESTAMPTZ,
        created_by INTEGER,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`;
      await sql`CREATE TABLE IF NOT EXISTS inventory_locations (
        item_id INTEGER NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
        location TEXT NOT NULL,
        PRIMARY KEY (item_id, location)
      )`;
      await sql`CREATE INDEX IF NOT EXISTS inventory_locations_loc_idx ON inventory_locations(location)`;
      await sql`CREATE TABLE IF NOT EXISTS inventory_reports (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        item_id INTEGER NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
        status TEXT NOT NULL,
        note TEXT NOT NULL DEFAULT '',
        user_id INTEGER,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`;
      await sql`CREATE INDEX IF NOT EXISTS inventory_reports_item_idx ON inventory_reports(item_id, created_at DESC)`;
      // 採購資訊：用完時自動送到採購申請
      await sql`ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS buy_link TEXT NOT NULL DEFAULT ''`;
      await sql`ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS unit_price DOUBLE PRECISION NOT NULL DEFAULT 0`;
      await sql`ALTER TABLE parts ADD COLUMN IF NOT EXISTS inventory_id INTEGER`;
    })().catch((err) => {
      schemaReady = null; // 下次請求再試
      throw err;
    });
  }
  return schemaReady;
}

type Row = Record<string, unknown>;

function toItem(r: Row): InventoryItem {
  const locs = (Array.isArray(r.locations) ? (r.locations as string[]) : []).filter(Boolean);
  return {
    id: Number(r.id),
    name: String(r.name),
    spec: String(r.spec ?? ""),
    category: String(r.category ?? ""),
    note: String(r.note ?? ""),
    buy_link: String(r.buy_link ?? ""),
    unit_price: Number(r.unit_price ?? 0) || 0,
    status: isInventoryStatus(r.status) ? r.status : "in_stock",
    locations: [...locs].sort(compareLocations),
    has_photo: Boolean(r.has_photo),
    status_note: String(r.status_note ?? ""),
    status_at: r.status_at ? new Date(r.status_at as string).toISOString() : null,
    status_by_name: (r.status_by_name as string | null) ?? null,
    created_at: new Date(r.created_at as string).toISOString(),
    updated_at: new Date(r.updated_at as string).toISOString(),
  };
}

export async function listInventory(): Promise<InventoryItem[]> {
  await ensureInventorySchema();
  const rows = await sql`
    SELECT i.id, i.name, i.spec, i.category, i.note, i.buy_link, i.unit_price, i.status, i.status_note, i.status_at,
           i.created_at, i.updated_at, (i.photo IS NOT NULL) AS has_photo,
           u.display_name AS status_by_name,
           COALESCE(array_agg(l.location) FILTER (WHERE l.location IS NOT NULL), '{}') AS locations
    FROM inventory_items i
    LEFT JOIN users u ON u.id = i.status_by
    LEFT JOIN inventory_locations l ON l.item_id = i.id
    GROUP BY i.id, u.display_name
    ORDER BY lower(i.name), i.id`;
  return rows.map((r) => toItem(r as Row));
}

export async function getInventoryItem(id: number): Promise<InventoryItemDetail | null> {
  await ensureInventorySchema();
  const [row] = await sql`
    SELECT i.*, (i.photo IS NOT NULL) AS has_photo, u.display_name AS status_by_name,
           COALESCE(array_agg(l.location) FILTER (WHERE l.location IS NOT NULL), '{}') AS locations
    FROM inventory_items i
    LEFT JOIN users u ON u.id = i.status_by
    LEFT JOIN inventory_locations l ON l.item_id = i.id
    WHERE i.id = ${id}
    GROUP BY i.id, u.display_name`;
  if (!row) return null;
  const reports = await sql`
    SELECT r.id, r.status, r.note, r.created_at, u.display_name AS user_name
    FROM inventory_reports r LEFT JOIN users u ON u.id = r.user_id
    WHERE r.item_id = ${id}
    ORDER BY r.created_at DESC, r.id DESC
    LIMIT 30`;
  return {
    ...toItem(row as Row),
    photo: (row.photo as string | null) ?? null,
    reports: reports.map((r) => ({
      id: Number(r.id),
      status: isInventoryStatus(r.status) ? r.status : "in_stock",
      note: String(r.note ?? ""),
      user_name: (r.user_name as string | null) ?? null,
      created_at: new Date(r.created_at as string).toISOString(),
    })) as InventoryReport[],
  };
}

/** 驗證並正規化位置清單；有無效代碼時回傳錯誤訊息 */
export function cleanLocations(raw: unknown): { locations: string[] } | { error: string } {
  if (!Array.isArray(raw)) return { locations: [] };
  const out = new Set<string>();
  for (const v of raw) {
    const norm = normalizeLocation(String(v ?? ""));
    if (!norm) return { error: "位置代碼無效（例如 7-12、4-A-14）" };
    out.add(norm);
  }
  if (out.size > 20) return { error: "位置太多了（最多 20 個）" };
  return { locations: [...out] };
}

/** 照片：只接受縮小後的 JPEG/PNG/WebP data URL（約 400KB 以內） */
export function cleanPhoto(raw: unknown): string | null | undefined | { error: string } {
  if (raw === undefined) return undefined;
  if (raw === null || raw === "") return null;
  const s = String(raw);
  if (!/^data:image\/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$/.test(s)) return { error: "照片格式不支援" };
  if (s.length > 550_000) return { error: "照片太大，請換一張" };
  return s;
}

export async function replaceLocations(itemId: number, locations: string[]) {
  await sql`DELETE FROM inventory_locations WHERE item_id = ${itemId}`;
  if (locations.length === 0) return;
  await sql`
    INSERT INTO inventory_locations (item_id, location)
    SELECT ${itemId}, unnest(${locations}::text[])
    ON CONFLICT DO NOTHING`;
}

export async function recordStatus(itemId: number, status: InventoryStatus, note: string, userId: number) {
  await sql`
    UPDATE inventory_items
    SET status = ${status}, status_note = ${note}, status_by = ${userId}, status_at = now(), updated_at = now()
    WHERE id = ${itemId}`;
  await sql`
    INSERT INTO inventory_reports (item_id, status, note, user_id)
    VALUES (${itemId}, ${status}, ${note}, ${userId})`;
}

/**
 * 物品被回報「沒有了」時，自動在採購申請開一筆待審批的補貨需求。
 * 如果這個物品已經有還沒到貨的申請（待審批／已核准／已下單），就不重複開。
 */
export async function autoRestockRequest(
  item: InventoryItem,
  user: { id: number; display_name: string },
  origin: string
): Promise<{ created: boolean; partId: number | null }> {
  await ensureInventorySchema();
  const [open] = await sql`
    SELECT id FROM parts
    WHERE inventory_id = ${item.id} AND status IN ('pending', 'approved', 'ordered')
    ORDER BY id DESC LIMIT 1`;
  if (open) return { created: false, partId: Number(open.id) };
  const where = item.locations.join(", ") || "未指定";
  const partId = await createPartRequest(
    {
      name: item.name,
      spec: item.spec,
      link: item.buy_link,
      qty: 1,
      est_price: item.unit_price,
      purpose: `庫存補貨：已用完（位置 ${where}）`,
    },
    user,
    origin
  );
  await sql`UPDATE parts SET inventory_id = ${item.id} WHERE id = ${partId}`;
  return { created: true, partId };
}
